const STRINGS: Record<Lang, AdminStrings> = { az, ru, en };
const STORAGE_KEY = 'soulart-admin-lang';

/** Language of the panel itself; separate from the language of the content being edited. */
let current: Lang = readStoredLang(STORAGE_KEY) ?? DEFAULT_LANG;

/** For code outside components, such as image processing errors. */
export const adminStrings = () => STRINGS[current];

const Context = createContext<{ lang: Lang; setLang: (lang: Lang) => void }>({ lang: DEFAULT_LANG, setLang: () => {} });

export function AdminLangProvider({ children }: { children: ReactNode }) {
  const [lang, setState] = useState<Lang>(current);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = (next: Lang) => {
    current = next;
    storeLang(STORAGE_KEY, next);
    setState(next);
  };
  return <Context.Provider value={{ lang, setLang }}>{children}</Context.Provider>;
}

export const useT = () => STRINGS[useContext(Context).lang];
export const useAdminLang = () => useContext(Context).lang;

export function AdminLanguageSwitch() {
  const { lang, setLang } = useContext(Context);
  const t = STRINGS[lang];
  return (
    <div className="admin-lang" role="group" aria-label={t.interfaceLanguage}>
      {LANGS.map((code) => (
        <button key={code} type="button" lang={code} aria-label={LANG_INFO[code].name} aria-pressed={code === lang} onClick={() => setLang(code)}>
          {LANG_INFO[code].short}
        </button>
      ))}
    </div>
  );
}
